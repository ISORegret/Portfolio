// Simple data source for your projects (events/listings/sets)
// Option 2: Images are stored in public/gallery/[folder]/ and served from your site.
// Paths below match the actual files in each folder (any naming works).

export type Project = {
  slug: string
  title: string
  category: 'Automotive' | 'Real Estate' | 'Street'
  date: string
  cover: string
  /** Pixieset (or other) link for “View full album”; omit when hosting only on-site images */
  album?: string
  /**
   * Lightbox downloads: `open` = anyone; `code` + `downloadCode` = Pixieset-style unlock (sessionStorage);
   * `none` = no download. Prefer setting explicitly on each album in `projects` (see comment above the array).
   */
  downloadAccess?: 'none' | 'open' | 'code'
  /** Required when `downloadAccess` is `'code'` (share with client like Pixieset). */
  downloadCode?: string
  blurb?: string
  images?: string[]
};

/** URL-safe folder name from project slug */
export function slugToFolder(slug: string): string {
  return slug.toLowerCase().replace(/\s+/g, '-');
}

export function getProjectBySlug(slug: string): Project | undefined {
  const decoded = decodeURIComponent(slug);
  return projects.find((p) => p.slug === decoded);
}

